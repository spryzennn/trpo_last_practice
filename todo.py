"""PostgreSQL-backed to-do organizer routes, isolated from the text editor."""
import os
from datetime import date

import psycopg
from psycopg.rows import dict_row
from flask import Blueprint, jsonify, render_template, request


todo_bp = Blueprint("todo", __name__)


def get_connection():
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError(
            "Не задан DATABASE_URL. Укажите строку подключения к PostgreSQL в переменных окружения."
        )
    return psycopg.connect(database_url, row_factory=dict_row)


def init_db():
    """Create the organizer table if it does not exist."""
    with get_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS todo_tasks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title VARCHAR(200) NOT NULL CHECK (char_length(trim(title)) > 0),
                description TEXT NOT NULL DEFAULT '',
                priority VARCHAR(10) NOT NULL DEFAULT 'medium'
                    CHECK (priority IN ('low', 'medium', 'high')),
                due_date DATE,
                is_completed BOOLEAN NOT NULL DEFAULT FALSE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)


@todo_bp.before_app_request
def ensure_database():
    # Initialize only for organizer routes; don't make the editor depend on PostgreSQL.
    if request.path == "/todo" or request.path.startswith("/api/todo"):
        try:
            init_db()
        except Exception as exc:
            if request.path == "/todo":
                return render_template("todo.html", active_page="todo", db_error=str(exc)), 503
            return jsonify(error=f"Не удалось подключиться к PostgreSQL: {exc}"), 503


@todo_bp.get("/todo")
def index():
    return render_template("todo.html", active_page="todo", db_error=None)


@todo_bp.get("/api/todo/tasks")
def list_tasks():
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT id, title, description, priority, due_date, is_completed,
                   created_at, updated_at
            FROM todo_tasks
            ORDER BY is_completed ASC, due_date ASC NULLS LAST, created_at DESC
        """).fetchall()
    for row in rows:
        row["id"] = int(row["id"])
        row["due_date"] = row["due_date"].isoformat() if row["due_date"] else None
        row["created_at"] = row["created_at"].isoformat()
        row["updated_at"] = row["updated_at"].isoformat()
    return jsonify(rows)


@todo_bp.post("/api/todo/tasks")
def create_task():
    data = request.get_json(silent=True) or {}
    title = str(data.get("title", "")).strip()
    if not title:
        return jsonify(error="Введите название задачи."), 400
    if len(title) > 200:
        return jsonify(error="Название задачи не должно превышать 200 символов."), 400
    priority = data.get("priority", "medium")
    if priority not in ("low", "medium", "high"):
        return jsonify(error="Некорректный приоритет."), 400
    due_date = data.get("due_date") or None
    if due_date:
        try:
            date.fromisoformat(due_date)
        except (TypeError, ValueError):
            return jsonify(error="Укажите корректную дату."), 400
    description = str(data.get("description", "")).strip()
    with get_connection() as conn:
        row = conn.execute("""
            INSERT INTO todo_tasks (title, description, priority, due_date)
            VALUES (%s, %s, %s, %s)
            RETURNING id, title, description, priority, due_date, is_completed,
                      created_at, updated_at
        """, (title, description, priority, due_date)).fetchone()
    row["id"] = int(row["id"])
    row["due_date"] = row["due_date"].isoformat() if row["due_date"] else None
    row["created_at"] = row["created_at"].isoformat()
    row["updated_at"] = row["updated_at"].isoformat()
    return jsonify(row), 201


@todo_bp.patch("/api/todo/tasks/<int:task_id>")
def update_task(task_id):
    data = request.get_json(silent=True) or {}
    allowed = {"title", "description", "priority", "due_date", "is_completed"}
    if not data or not set(data).issubset(allowed):
        return jsonify(error="Нет изменений или переданы неизвестные поля."), 400
    updates = {}
    if "title" in data:
        title = str(data["title"]).strip()
        if not title or len(title) > 200:
            return jsonify(error="Название должно содержать от 1 до 200 символов."), 400
        updates["title"] = title
    if "description" in data:
        updates["description"] = str(data["description"]).strip()
    if "priority" in data:
        if data["priority"] not in ("low", "medium", "high"):
            return jsonify(error="Некорректный приоритет."), 400
        updates["priority"] = data["priority"]
    if "due_date" in data:
        due_date = data["due_date"] or None
        if due_date:
            try:
                date.fromisoformat(due_date)
            except (TypeError, ValueError):
                return jsonify(error="Укажите корректную дату."), 400
        updates["due_date"] = due_date
    if "is_completed" in data:
        if not isinstance(data["is_completed"], bool):
            return jsonify(error="Статус должен быть логическим значением."), 400
        updates["is_completed"] = data["is_completed"]

    assignments = ", ".join(f"{field} = %s" for field in updates)
    values = list(updates.values()) + [task_id]
    with get_connection() as conn:
        row = conn.execute(
            f"""UPDATE todo_tasks SET {assignments}, updated_at = CURRENT_TIMESTAMP
                WHERE id = %s
                RETURNING id, title, description, priority, due_date, is_completed,
                          created_at, updated_at""",
            values,
        ).fetchone()
    if row is None:
        return jsonify(error="Задача не найдена."), 404
    row["id"] = int(row["id"])
    row["due_date"] = row["due_date"].isoformat() if row["due_date"] else None
    row["created_at"] = row["created_at"].isoformat()
    row["updated_at"] = row["updated_at"].isoformat()
    return jsonify(row)


@todo_bp.delete("/api/todo/tasks/<int:task_id>")
def delete_task(task_id):
    with get_connection() as conn:
        result = conn.execute("DELETE FROM todo_tasks WHERE id = %s", (task_id,))
    if result.rowcount == 0:
        return jsonify(error="Задача не найдена."), 404
    return jsonify(message="Задача удалена.")
